DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mcp_ro') THEN CREATE ROLE mcp_ro NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mcp_rw') THEN CREATE ROLE mcp_rw NOLOGIN; END IF;
END $$;
ALTER ROLE mcp_ro NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
ALTER ROLE mcp_rw NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM mcp_ro, mcp_rw;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM mcp_ro, mcp_rw;
GRANT USAGE ON SCHEMA public TO mcp_ro, mcp_rw;
GRANT SELECT ON public.orders TO mcp_ro;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.orders TO mcp_rw;
GRANT USAGE, SELECT ON SEQUENCE public.orders_id_seq TO mcp_rw;
DO $$ BEGIN
  EXECUTE format('REVOKE TEMPORARY, CREATE ON DATABASE %I FROM PUBLIC', current_database());
  EXECUTE format('GRANT CONNECT ON DATABASE %I TO mcp_ro, mcp_rw', current_database());
END $$;
